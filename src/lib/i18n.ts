export const DICTS: Record<Locale, Record<DictKey, string>> = { es, pt };

/** Interpolación simple: t('c.cuponOk', { code: 'ÑANDUTI' }). */
export function translate(locale: Locale, key: DictKey, vars?: Record<string, string | number>): string {
  const raw = DICTS[locale][key] ?? DICTS.es[key] ?? String(key);
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
